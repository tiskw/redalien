// Include the primary header.
#include "pipe.hxx"

// Include POSIX headers.
#include <fcntl.h>
#include <unistd.h>

////////////////////////////////////////////////////////////////////////////////////////////////////
// Public functions
////////////////////////////////////////////////////////////////////////////////////////////////////

Pipe::Pipe(void) : fds{-1, -1}
{ /* Initializer list only. */ }

Pipe::~Pipe(void)
{ this->close_r(); this->close_w(); }

////////////////////////////////////////////////////////////////////////////////////////////////////
// Public functions
////////////////////////////////////////////////////////////////////////////////////////////////////

void Pipe::close_r(void) noexcept { close_fd(this->fds[0]); }
void Pipe::close_w(void) noexcept { close_fd(this->fds[1]); }

int Pipe::fd_r(void) const noexcept { return this->fds[0]; }
int Pipe::fd_w(void) const noexcept { return this->fds[1]; }

bool Pipe::open(void) noexcept
{   // {{{

    return pipe2(this->fds, O_CLOEXEC) == 0;

}   // }}}

void Pipe::set_read_nonblock(void) noexcept
{   // {{{

    if (this->fds[0] >= 0)
        fcntl(this->fds[0], F_SETFL, fcntl(this->fds[0], F_GETFL) | O_NONBLOCK);

}   // }}}

////////////////////////////////////////////////////////////////////////////////////////////////////
// Static functions
////////////////////////////////////////////////////////////////////////////////////////////////////

void Pipe::close_fd(int& fd) noexcept
{   // {{{

    // Close the file descriptor if it is valid,
    // and set it to -1 to indicate that it is closed.
    if (fd >= 0) { close(fd); fd = -1; }

}   // }}}

